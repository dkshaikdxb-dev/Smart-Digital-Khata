// Lightweight i18n for the native OWNER app. A flat key -> string map per
// language, a t() with {var} interpolation, and a language setter persisted in
// expo-secure-store under a key DISTINCT from the consumer app's. Offline-first,
// no network. en is the source of truth; every t('…') call site resolves against
// en first if the active language lacks a key, and finally against the raw key,
// so nothing on the UI ever renders blank or as a key name.
//
// en + hi are fully authored. ta/te/kn/ml/ur reuse the owner-facing strings
// already translated in the web dashboard (admin-dashboard/src/lib/i18n.js) where
// they map, and fall back to English elsewhere. bn/gu/mr are authored HERE (batch
// LANG): every key whose concept already exists in mobile-app/src/consumer/i18n.js
// reuses that exact consumer string so the two flavors speak with one voice, and
// the rest is written in the same plain shopkeeper register. They have NOT yet
// been read by a native speaker — docs/i18n-review-bn-gu-mr.md is the review sheet
// and the source of truth for corrections, and they keep the "(beta)" marker in
// the picker until that review lands. All ten are fully selectable in Settings.
//
// A key is deliberately ABSENT where the English fallback already renders exactly
// right — a brand name ('txn.upi' is "UPI" in every source that has it), "HH:MM",
// "Razorpay Key ID". Absent beats a row that changes nothing on screen.
//
// Real coverage per language is NOT 100% and is not claimed to be. The repo-root
// scripts/i18n-coverage.mjs measures it against en and fails CI on a regression.

