// en is the source of truth (every key). hi is fully authored. ta/te/kn/ml/ur are
// authored where a web-dashboard string maps and fall back to en otherwise. bn/gu/mr
// carry no entries yet and fall back to en entirely.
const DICTS = {
  en,
  hi,
  bn,
  ta,
  te,
  kn,
  ml,
  mr,
  gu,
  ur,
};

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}

// Pure translate: chosen language, then English, then the raw key — so a string
// is never blank and never a bare key on screen.
export function translate(lang, key, vars) {
  const dict = DICTS[lang] || en;
  const s = dict[key] != null ? dict[key] : (en[key] != null ? en[key] : key);
  return interpolate(s, vars);
}

// Best-effort 2-letter device language, falling back to 'en'. Never throws.
function deviceLang() {
  try {
    let loc = '';
    if (Platform.OS === 'ios') {
      const s = NativeModules.SettingsManager && NativeModules.SettingsManager.settings;
      loc = (s && (s.AppleLocale || (s.AppleLanguages && s.AppleLanguages[0]))) || '';
    } else {
      loc = (NativeModules.I18nManager && NativeModules.I18nManager.localeIdentifier) || '';
    }
    const two = String(loc).slice(0, 2).toLowerCase();
    return DICTS[two] ? two : 'en';
  } catch (e) {
    return 'en';
  }
}

async function loadStoredLang() {
  try {
    const v = await SecureStore.getItemAsync(LANG_KEY);
    if (v && DICTS[v]) return v;
  } catch (e) { /* ignore */ }
  return deviceLang();
}

const LangContext = createContext({
  lang: 'en',
  t: (k, vars) => translate('en', k, vars),
  setLang: () => {},
});

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState('en');

  useEffect(() => {
    let alive = true;
    loadStoredLang().then((l) => { if (alive) setLangState(l); });
    return () => { alive = false; };
  }, []);

  const setLang = useCallback((l) => {
    if (!DICTS[l]) return;
    setLangState(l);
    SecureStore.setItemAsync(LANG_KEY, l).catch(() => {});
  }, []);

  const value = useMemo(() => ({
    lang,
    setLang,
    t: (key, vars) => translate(lang, key, vars),
  }), [lang, setLang]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useT() {
  return useContext(LangContext);
}
